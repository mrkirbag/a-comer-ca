export function telHref(raw: string) {
    return raw ? `tel:${raw}` : "#";
}

export function waHref(raw: string, message?: string) {
    if (!raw) return "#";
    const text = message ? `?text=${encodeURIComponent(message)}` : "";
    return `https://wa.me/${raw.replace(/\D/g, "")}${text}`;
}
